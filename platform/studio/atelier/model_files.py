"""Model-source membership and retirement inside a single producer-owned generated folder."""
from pathlib import Path, PurePosixPath
import stat


def member(value):
    if (not isinstance(value, str) or not value or not PurePosixPath(value).parts or '\\' in value
            or PurePosixPath(value).is_absolute() or PurePosixPath(value).as_posix() != value
            or any(part in ('.', '..') for part in PurePosixPath(value).parts)):
        raise ValueError('Model sources require canonical relative members')
    return value


def source_records(meshes, *, collision_directory=None):
    """One mapping for source checks and retirement; boolean collision flags are not hulls."""
    result = []
    for mesh in meshes:
        result.append((mesh, member(mesh['path'])))
        collision = mesh.get('collision')
        if collision is None or type(collision) is bool:
            continue
        if (not isinstance(collision, dict) or not isinstance(collision.get('path'), str)
                or not collision['path'] or not isinstance(collision.get('sha256'), str)):
            raise ValueError('Invalid region collision-source record')
        path = member(collision['path'])
        if collision_directory is not None:
            path = member(collision_directory) + '/' + PurePosixPath(path).name
        result.append((collision, path))
    return result


def regular_files(root):
    """Inspect regular members without following root/member links or accepting special entries."""
    root = Path(root)
    if not stat.S_ISDIR(root.lstat().st_mode):
        raise ValueError('Generated model root must be a regular directory')
    found = set()
    def visit(path):
        mode = path.lstat().st_mode
        if stat.S_ISDIR(mode):
            for child in sorted(path.iterdir()): visit(child)
        elif stat.S_ISREG(mode):
            found.add(path.relative_to(root).as_posix())
        else:
            raise ValueError('Generated model trees require regular files and directories')
    visit(root)
    return found


def retain_files(root, expected):
    """@cc [owner:fontanierh,label:correctness] retire-superseded-generated-members
    Only a producer with exclusive write ownership MAY retire files in its generated root.
    Every required current member MUST exist as a regular file before any removal. Linked,
    special, escaping or incomplete trees MUST refuse without deleting anything. Retirement
    MUST remove only undeclared files inside that root, never committed sources or sibling outputs.
    This membership operation MUST NOT certify generated bytes or publish a success stamp.
    """
    root = Path(root)
    absolute = root.absolute()
    if any(path.is_symlink() for path in (absolute, *absolute.parents)):
        raise ValueError('Generated model retirement requires canonical unlinked ancestors')
    expected = {member(path) for path in expected}
    actual = regular_files(root)
    if not expected or not expected <= actual:
        raise ValueError('Current generated model membership is empty or incomplete')
    retired = sorted(actual - expected)
    for name in retired:
        (root / name).unlink()
    return retired
