def declared(ctx, step):
    from .build import UnrealCompile, UnrealPackage
    result = [p for product in step.products for p in product.roots()]
    result += list(getattr(step, 'checkpoint_outputs', ()))
    if any(isinstance(c, UnrealCompile) for c in step.commands):
        result += compile_outputs(ctx, step)
    for command in step.commands:
        if isinstance(command, UnrealPackage):
            # Source-bound cook receipts are regenerated by the normal Call commands after
            # a payload restore. Git provenance must not enter the payload's reuse key.
            result += [command.archive]
    result = list(dict.fromkeys(map(Path, result)))
    # Keep only outermost roots; overlapping products have already been rejected by the recipe graph.
    selected = set(result)
    return [p for p in result if not any(parent in selected for parent in p.parents)]


def source_scopes(sources):
    """@cc [owner:fontanierh,label:correctness] tracked-source-containment
    Membership MUST be equivalent to a tracked source or any of its lexical parents.
    Source inventories MUST remain fresh per check; no filesystem/index state MAY be
    cached across publication or restoration checks. Paths MUST NOT be resolved differently.
    """
    result = set()
    for source in sources:
        # A previously visited parent already contributed its complete ancestor
        # chain in this check. Do not rebuild that chain for every sibling file.
        while source not in result:
            result.add(source)
            source = source.parent
    return result


def compile_outputs(ctx, step):
    project = getattr(ctx, 'uproject', None)
    if project is None:
        return []
    output = project.parent / 'Binaries/Mac'
    modules = json.loads(project.read_text()).get('Modules', [])
    result = [output / 'UnrealEditor.modules']
    for module in modules:
        if module.get('Type') != 'ServerOnly':
            result += [output / ('libUnrealEditor-' + module['Name'] + '.dylib'),
                       output / ('libUnrealEditor-' + module['Name'] + '.dylib.dSYM')]
    from .build import UnrealCompile
    result += [output / (c.target + '.target') for c in step.commands if isinstance(c, UnrealCompile)]
    for base in (paths.ENGINE_PLUGINS, project.parent / 'Plugins'):
        for descriptor in sorted(base.rglob('*.uplugin')) if base.exists() else ():
            if any(p in ('Binaries', 'Intermediate') for p in descriptor.relative_to(base).parts):
                continue
            binaries = descriptor.parent / 'Binaries/Mac'
            result.append(binaries / 'UnrealEditor.modules')
            for module in json.loads(descriptor.read_text()).get('Modules', []):
                result += [output / ('libUnrealEditor-' + module['Name'] + '.dylib'),
                           output / ('libUnrealEditor-' + module['Name'] + '.dylib.dSYM')]
                result += [binaries / ('libUnrealEditor-' + module['Name'] + '.dylib'),
                           binaries / ('libUnrealEditor-' + module['Name'] + '.dylib.dSYM')]
    return result


def compile_present(ctx, step):
    from .build import UnrealCompile
    if not any(isinstance(c, UnrealCompile) for c in step.commands):
        return True
    project = getattr(ctx, 'uproject', None)
    if project is None:
        return False
    output = project.parent / 'Binaries/Mac'
    required = [output / 'UnrealEditor.modules']
    required += [output / ('libUnrealEditor-' + m['Name'] + '.dylib')
                 for m in json.loads(project.read_text()).get('Modules', []) if m.get('Type') != 'ServerOnly']
    try:
        allowed = set(compile_outputs(ctx, step))
        engine = getattr(ctx, 'unreal_root', None)
        engine_id = read_json(engine / 'Engine/Binaries/Mac/UnrealEditor.modules').get('BuildId') if engine else None
        if engine is not None and (not engine_id or read_json(output / 'UnrealEditor.modules').get('BuildId') != engine_id):
            return False
        for command in step.commands:
            if not isinstance(command, UnrealCompile):
                continue
            receipt = output / (command.target + '.target')
            required.append(receipt)
            value = read_json(receipt)
            if (value.get('TargetName') != command.target or value.get('Platform') != 'Mac'
                    or (engine_id and value.get('Version', {}).get('BuildId') != engine_id)):
                return False
            for item in value.get('BuildProducts', []):
                name = item['Path']
                if name.startswith('$(EngineDir)/'):
                    continue  # The installed engine is separately fingerprinted and retained.
                if name.startswith('$(ProjectDir)/'):
                    path = project.parent / name[len('$(ProjectDir)/'):]
                else:
                    path = Path(name)
                    if not path.is_absolute():
                        path = receipt.parent / path
                path = Path(os.path.normpath(path.absolute()))
                if path not in allowed:
                    return False
                required.append(path)
        return all(p.is_file() and not p.is_symlink() for p in required)
    except (OSError, ValueError, KeyError, TypeError):
        return False


def label(ctx, path):
    choices = [(name, root) for name, (root, _) in roots(ctx).items() if path == root or root in path.parents]
    if not choices:
        raise CheckpointError('Task output is outside checkpoint-owned generated directories')
    name, root = max(choices, key=lambda item: len(item[1].parts))
    tail = path.relative_to(root).as_posix()
    return name if tail == '.' else name + '/' + tail


def destination(ctx, name):
    part, _, tail = name.partition('/')
    allowed = roots(ctx)
    if part not in allowed:
        raise CheckpointError('Task output root is not locally owned')
    root = allowed[part][0]
    return safe_destination(root, tail) if tail else safe_destination(root.parent, root.name)


def key(ctx, step, fingerprint, *, require_outputs=True):
    from .build import Blender
    # Ambient Blender startup is not portable producer proof. Existing local incremental
    # state can continue, but these commands do not publish transferable action entries.
    if any(isinstance(c, Blender) and not c.factory_startup for c in step.commands):
        return None
    outputs = declared(ctx, step)
    if not outputs and require_outputs:
        return None
    if not hasattr(ctx, 'checkpoint_tool_context'):
        ctx.checkpoint_tool_context = context(ctx)
    tool = dict(ctx.checkpoint_tool_context)
    from .build import Python, Blender, UnrealScript, UnrealCompile, UnrealPackage
    if not any(isinstance(c, (UnrealScript, UnrealCompile, UnrealPackage)) for c in step.commands):
        tool = {name: value for name, value in tool.items() if name in ('system', 'machine')}
    if any(isinstance(c, (Python, Blender)) for c in step.commands):
        from .build_cache import tool_context
        from .build_hashes import HashIndex
        with HashIndex(paths.cache_dir('checkpoints') / 'tool-hashes.sqlite3') as index:
            from dataclasses import fields, replace
            commands = [base(**{f.name: getattr(c, f.name) for f in fields(base)})
                        for c in step.commands for base in (Python, Blender) if isinstance(c, base)]
            source_step = replace(step, commands=commands)
            tool['source_tools'] = tool_context(source_step, index.digest, cache=ctx.__dict__.setdefault('checkpoint_source_tool_cache', {}))
    return identity(dict(schema=1, game=ctx.game, task=step.name, fingerprint=fingerprint,
                         outputs=[label(ctx, p) for p in outputs], tool=tool))


def load(store, action_key):
    path = entry_path(store, action_key)
    return validate(read_json(path), store, action_key) if path.exists() else None


def snapshot(ctx, step, store, *, save_blobs, observations=None):
    declarations, files = [], {}
    sources = source_scopes(tracked_paths())
    for root in declared(ctx, step):
        name = label(ctx, root)
        if root in sources:
            raise CheckpointError('Task output scope contains tracked source')
        if root.is_symlink():
            raise CheckpointError('Task cache root must not be linked')
        if observations is not None:
            observations[str(root)] = list(signature(root.lstat())) if root.exists() else None
        if not root.exists():
            if root in getattr(step, 'checkpoint_outputs', ()):
                raise CheckpointError('Required checkpoint output root is missing')
            declarations.append(dict(path=name, kind='absent'))
            continue
        declarations.append(dict(path=name, kind='directory' if root.is_dir() else 'file'))
        leaves = list(members(root)) if root.is_dir() else [root]
        if root.is_dir():
            leaves += [p for p in root.rglob('*') if p.is_dir() and not p.is_symlink()
                       and not any(parent.is_symlink() for parent in p.parents if parent != root)]
        for path in leaves:
            info = path.lstat()
            if observations is not None:
                observations[str(path)] = list(signature(info))
            if stat.S_ISLNK(info.st_mode):
                target = path.resolve(strict=True)
                if getattr(ctx, 'unreal_root', None) and target.is_relative_to(ctx.unreal_root):
                    link = 'engine:' + target.relative_to(ctx.unreal_root).as_posix()
                elif any(target == p or p in target.parents for p in declared(ctx, step)):
                    link = 'member:' + label(ctx, target)
                else:
                    raise CheckpointError('Task output link escapes its declared artifact and engine')
                files[label(ctx, path)] = dict(kind='link', target=link, mode=stat.S_IMODE(info.st_mode),
                                               mtime_ns=info.st_mtime_ns)
                continue
            if stat.S_ISDIR(info.st_mode):
                files[label(ctx, path)] = dict(kind='directory', mode=stat.S_IMODE(info.st_mode), mtime_ns=info.st_mtime_ns)
                continue
            if not stat.S_ISREG(info.st_mode):
                raise CheckpointError('Special task cache output')
            hasher = getattr(ctx, 'checkpoint_hasher', None)
            digest = (hasher or build_products.file_digest)(path)
            if save_blobs:
                store.put(path, digest, **({'proved': signature(info)} if getattr(hasher, 'proves', False) else {}))
            files[label(ctx, path)] = dict(kind='file', size=info.st_size, sha256=digest,
                                           mode=stat.S_IMODE(info.st_mode), mtime_ns=info.st_mtime_ns)
    if observations is not None:
        check_observations(observations)
    return declarations, files


def check_observations(observations):
    for name, expected in observations.items():
        path = Path(name)
        observed = list(signature(path.lstat())) if path.exists() or path.is_symlink() else None
        if observed != expected:
            raise CheckpointError('Published output metadata changed; run the normal incremental build')


def equivalent(left, right):
    """Write times are restored metadata, not output content or determinism evidence."""
    def normalize(value):
        return {name: {k: v for k, v in entry.items() if k != 'mtime_ns'} for name, entry in value.items()}
    return normalize(left) == normalize(right)


def publish(ctx, step, fingerprint, stamp, *, store=None, done=None, produced=False):
    """@cc [owner:fontanierh,label:correctness] complete-task-result-publication
    A reusable task entry MUST have complete declared outputs and fresh input/product proof.
    Only a completed execution/verified restoration MAY bind a new producer tool key and output
    inventory identity; an existing legacy stamp MUST NOT be adopted under currently selected tools.
    It MUST NOT infer completeness from changed-file observations or representative legacy outputs.
    Identical input/tool keys producing different output bytes MUST be disabled, never overwritten.
    """
    store = store or Store(ctx.game)
    action_key = key(ctx, step, fingerprint)
    if action_key is None or stamp.get('touched'):
        return None
    from .build import fingerprint as receiving_fingerprint
    if done is None:
        raise CheckpointError('Task publication requires its verified dependency results')
    # Installed tools are fixed for this build invocation. Keep the same complete resource memo
    # used for planning; tool executables are hashed once per stat signature (tool_digest).
    # Source inputs still get fresh byte checks through the build's index in verify mode.
    tools = getattr(ctx, 'build_tool_cache', None)
    index = getattr(ctx, 'build_hash_index', None)
    fresh = None if index is None else SimpleNamespace(digest=lambda path: index.digest(path, verify=True), verify=True)

    def inputs_unchanged():
        return receiving_fingerprint(step, done, index=fresh, tool_cache=tools) == fingerprint

    if not inputs_unchanged():
        raise CheckpointError('Task inputs changed before publication')
    if step.products and build_products.records(step) != stamp.get('products'):
        raise CheckpointError('Task products changed before publication')
    if not compile_present(ctx, step):
        raise CheckpointError('Compiled target is missing required module binaries or its registry')
    from .checkpoint_store import hashing
    digest = index.proving_digest if index is not None else None
    # Every walk, hash and copy happens before store.lock; the lock only guards the entry write
    # against concurrent retention, so other builds never wait on this action's hashing.
    with hashing(ctx, digest):
        declarations, files = snapshot(ctx, step, store, save_blobs=True)
        proof = inventory_identity(declarations, files)
        if not produced and (stamp.get('checkpoint_key') != action_key or stamp.get('checkpoint_inventory') != proof):
            raise CheckpointError('Existing output bytes lack compatible producer tool/inventory proof')
        observations = {}
        second_roots, second_files = snapshot(ctx, step, store, save_blobs=False, observations=observations)
    if (declarations != second_roots or not equivalent(files, second_files)
            or not inputs_unchanged() or key(ctx, step, fingerprint) != action_key):
        raise CheckpointError('Task inputs or outputs changed during publication')
    stamp['checkpoint_key'] = action_key
    stamp['checkpoint_inventory'] = proof
    value = dict(schema=1, game=ctx.game, key=action_key, task=step.name, fingerprint=fingerprint,
                 roots=declarations, files=files, stamp=stamp)
    validate(value, store, action_key)
    with store.locked():
        # Retention may have run since the blobs were stored: metadata checks only, no hashing.
        if any(entry['kind'] == 'file' and not (store.blob(entry['sha256']).is_file()
                                                and store.blob(entry['sha256']).stat().st_size == entry['size'])
               for entry in files.values()):
            raise CheckpointError('Task output blobs were collected during publication')
        previous = load(store, action_key)
        if previous and (previous['roots'] != declarations or not equivalent(previous['files'], files)):
            atomic_json(entry_path(store, action_key).with_suffix('.conflict'), {'key': action_key})
            raise CheckpointError('Identical task inputs produced different outputs; cache entry disabled')
        atomic_json(entry_path(store, action_key), value)
    ctx.__dict__.setdefault('retention_observations', {})[step.name] = observations
    return action_key


def valid_outputs(ctx, step, value):
    try:
        declarations, files = snapshot(ctx, step, Store(ctx.game), save_blobs=False)
        return declarations == value['roots'] and equivalent(files, value['files'])
    except (OSError, ValueError, RuntimeError):
        return False


def restore_worker(ctx, step, store, action_key, *, labels=None, hashes=None):
    """Owned output replacement: clones of verified blobs, in the build process or a worker.

    With labels (the parent's declared output labels) no recipe is needed; the parent still
    verifies the complete restored inventory against the recipe after the guard closes.
    With hashes (the build's open hash index) restored digests are recorded there directly.
    """
    value = load(store, action_key)
    if value is None or entry_path(store, action_key).with_suffix('.conflict').exists():
        raise CheckpointError('Task cache entry is missing or disabled')
    task = step.name if step is not None else value['task']
    expected = [label(ctx, p) for p in declared(ctx, step)] if step is not None else list(labels)
    if 'tracked_source_scopes' not in ctx.__dict__:  # Tracked files do not change within a build.
        ctx.tracked_source_scopes = source_scopes(tracked_paths())
    sources = ctx.tracked_source_scopes
    if any(destination(ctx, name) in sources for name in expected):
        raise CheckpointError('Task restoration cannot replace tracked source')
    if [r['path'] for r in value['roots']] != expected:
        raise CheckpointError('Task output declarations changed')
    journal = ctx.out / JOURNAL
    receipt = dict(schema=1, game=ctx.game, key=action_key, task=task, operation='action')
    from .build_snapshot import require_complete
    require_complete(ctx.out, game=ctx.game, checkpoint_resume=receipt)
    if journal.exists() and read_json(journal) != receipt:
        raise CheckpointError('Another checkpoint restoration is incomplete')
    for name, entry in value['files'].items():
        destination(ctx, name)
        if entry['kind'] != 'file':
            continue
        blob = store.blob(entry['sha256'])
        # Blobs are verified when stored; a wrong identity disables the entry, never the build.
        if not blob.is_file() or blob.is_symlink() or blob.stat().st_size != entry['size']:
            atomic_json(entry_path(store, action_key).with_suffix('.conflict'), {'key': action_key, 'reason': 'blob'})
            raise CheckpointError('Task cache blob is missing or corrupt; entry disabled')
    ctx.stamps.mkdir(parents=True, exist_ok=True)
    (ctx.stamps / (task + '.json')).unlink(missing_ok=True)
    atomic_json(journal, receipt)
    # Whole declared roots are replaced, including deletion of retired members. Other roots
    # and all tracked source stay outside the transaction's authority.
    for root in value['roots']:
        target = destination(ctx, root['path'])
        if target.is_symlink():
            raise CheckpointError('Task output became linked')
        if target.is_dir():
            shutil.rmtree(target)
        elif target.exists():
            target.unlink()
        if root['kind'] == 'directory':
            target.mkdir(parents=True, exist_ok=True)
    for name, entry in value['files'].items():
        target = destination(ctx, name)
        target.parent.mkdir(parents=True, exist_ok=True)
        if entry['kind'] == 'file':
            copy_file(store.blob(entry['sha256']), target)
            os.chmod(target, entry['mode'])
            os.utime(target, ns=(entry['mtime_ns'], entry['mtime_ns']))
        elif entry['kind'] == 'directory':
            target.mkdir(exist_ok=True)
        else:
            link = (ctx.unreal_root / entry['target'][7:] if entry['target'].startswith('engine:')
                    else destination(ctx, entry['target'][7:]))
            target.symlink_to(os.path.relpath(link, target.parent))
    for name, entry in reversed(list(value['files'].items())):
        if entry['kind'] == 'directory':
            os.chmod(destination(ctx, name), entry['mode'])
    from .checkpoint_store import RESTORED_HASHES, unchanged
    from .build_hashes import HashIndex
    from contextlib import nullcontext
    with (nullcontext(hashes) if hashes is not None else HashIndex(ctx.out / RESTORED_HASHES)) as index:
        for name, entry in value['files'].items():
            if entry['kind'] == 'file':
                target = destination(ctx, name)
                if not unchanged(target, entry):
                    raise CheckpointError('Restored task output differs; launch barrier retained')
                index.record(target, entry['sha256'])
    if step is not None and not restored_outputs(ctx, step, value):
        raise CheckpointError('Restored task output inventory differs; launch barrier retained')
    return value


def metadata_hasher(ctx, files):
    """Digest of a just-restored clone proved by its recorded size, mode and mtime; else read."""
    from .checkpoint_store import unchanged
    known = {str(destination(ctx, n)): e for n, e in files.items() if e['kind'] == 'file'}
    def digest(path):
        entry = known.get(str(path))
        if entry is not None and unchanged(Path(path), entry):
            return entry['sha256']
        return build_products.file_digest(path)
    return digest


def restored_outputs(ctx, step, value):
    """valid_outputs for a fresh restoration: complete inventory, metadata proof for clones."""
    from .checkpoint_store import hashing
    with hashing(ctx, metadata_hasher(ctx, value['files'])):
        return valid_outputs(ctx, step, value)


class Actions:
    def __init__(self, ctx, settings, echo=print):
        self.ctx, self.settings, self.echo = ctx, settings, echo
        self.store = Store(ctx.game)
        self.remote = None
        self.indices = []
        self.candidates = None
        self.misses = set()

    def get(self, step, fingerprint, *, local_only=False):
        action_key = key(self.ctx, step, fingerprint)
        if action_key is None or action_key in self.misses:
            return None
        if entry_path(self.store, action_key).with_suffix('.conflict').exists():
            raise CheckpointError('Task cache key is disabled after conflicting outputs')
        value = load(self.store, action_key)
        if value is not None:
            return value
        from .build_checkpoints import remote_repository
        if local_only or remote_repository(self.settings) is None:
            return None
        from .checkpoint_github import Remote
        if self.remote is None:
            self.remote = Remote(self.settings['repository'], self.ctx.game, echo=self.echo)
        if self.candidates is None:
            self.candidates = iter(self.remote.candidates())
        def entries():
            yield from self.indices
            with tempfile.TemporaryDirectory(dir=self.store.directory) as temporary:
                for item in self.candidates:
                    index = self.remote.descriptor(item, Path(temporary))
                    self.indices.append((item, index))
                    yield item, index
        with self.remote.transaction():
            for item, index in entries():
                from .checkpoint_archive import records
                history, history_blobs = records(index)
                value = index['checkpoint'].get('actions', {}).get(action_key, history.get(action_key))
                if value is None:
                    continue
                validate(value, self.store, action_key)
                subset = dict(index['checkpoint'], actions={}, files=value['files'], stamps={step.name: value['stamp']})
                needed = {e['sha256'] for e in value['files'].values() if e['kind'] == 'file'}
                locations = {**history_blobs, **index['blobs']}
                transfer = dict(index, checkpoint=subset, key=identity(subset),
                                blobs={digest: locations[digest] for digest in needed})
                self.remote.fetch(item, transfer, self.store, save=False)
                install(self.store, value)
                return value
        self.misses.add(action_key)
        return None

    def restore(self, step, fingerprint, value, done, *, index=None, tool_cache=None):
        """@cc [owner:fontanierh,label:safety;performance] in-process-action-restore
        A per-task action restore MUST only clone digest-named blobs verified when stored into
        that task's declared roots, under its durable launch barrier, inside the build process
        that already holds the build lock; it MUST NOT spawn a child or wait for admission.
        Inputs MUST be rechecked before and after, with the build's hash index, and the complete
        restored inventory MUST match before the barrier is cleared. Whole-workspace restores,
        hydration and other transfers keep the guarded worker lifecycle.
        """
        from .build import fingerprint as fresh
        def current():
            return fresh(step, done, index=index, tool_cache=tool_cache) if index is not None else fresh(step, done)
        if current() != fingerprint:
            raise CheckpointError('Inputs changed before task cache restoration')
        restored = restore_worker(self.ctx, step, self.store, value['key'], hashes=index)
        if restored.get('key') != value['key']:
            raise CheckpointError('Task restoration completion differs; launch barrier retained')
        if current() != fingerprint:
            raise CheckpointError('Inputs changed during task restoration; launch barrier retained')
        journal = self.ctx.out / JOURNAL
        expected = dict(schema=1, game=self.ctx.game, key=value['key'], task=step.name, operation='action')
        if read_json(journal) != expected:
            raise CheckpointError('Task restoration journal changed')
        # Parent execution writes its normal fresh certificate after all output/read checks.
        journal.unlink()
        from .store_retention import touch
        touch(self.store, value['key'])
        return True


def validate_ownership(ctx, steps):
    """Extra checkpoint roots obey the same disjoint ownership rule as named products."""
    declared_roots = []
    for step in steps:
        for root in declared(ctx, step):
            label(ctx, root)  # Must lie within locally allowed generated directories.
            # Case-insensitive APFS aliases cannot have separate owners.
            name = str(root.absolute()).casefold()
            for owner, previous in declared_roots:
                if owner != step.name and (name == previous or name.startswith(previous + '/') or previous.startswith(name + '/')):
                    raise CheckpointError('Checkpoint output scopes overlap: ' + owner + ' and ' + step.name)
            declared_roots.append((step.name, name))


def install(store, value):
    """Retain downloaded entries for offline reuse, refusing conflicting immutable results."""
    action_key = value['key']
    validate(value, store, action_key)
    with store.locked():
        path = entry_path(store, action_key)
        previous = load(store, action_key)
        if path.with_suffix('.conflict').exists():
            raise CheckpointError('Task cache key is disabled after conflicting outputs')
        if previous and (previous['roots'] != value['roots'] or not equivalent(previous['files'], value['files'])):
            atomic_json(path.with_suffix('.conflict'), dict(key=action_key))
            raise CheckpointError('Remote and local task results conflict; key disabled')
        atomic_json(path, value)


def verifiable(ctx, step):
    """@cc [owner:fontanierh,label:correctness] unverified-steps-never-publish
    A step whose stamp cannot be checked against complete output records (ambient Blender, or
    only representative outputs without a matching written-output inventory) MUST NOT publish
    its owned files or its stamp to a checkpoint manifest. Restoration and hydration MUST NOT
    adopt such a stamp or its owned files from the store, including from manifests published
    before this rule; the receiver rebuilds them. An inventoried stamp MAY be adopted only when
    every listed file was published with the recorded size, mtime and digest.
    """
    from .build import Blender, Call
    if any(isinstance(c, Blender) and not c.factory_startup for c in step.commands):
        return False
    if declared(ctx, step):
        return True
    return all(isinstance(c, Call) for c in step.commands) and not step.outputs


def ambient(step):
    from .build import Blender
    return any(isinstance(c, Blender) and not c.factory_startup for c in step.commands)


def inventory_verified(ctx, step, stamp):
    """A representative-output stamp whose complete written inventory still matches on disk."""
    from .output_inventory import changed
    inventory = stamp.get('output_inventory')
    return bool(inventory) and not ambient(step) and not changed(ctx, inventory)


def inventory_published(step, stamp, files):
    """A saved representative-output stamp whose every inventoried file was published intact."""
    inventory = stamp.get('output_inventory')
    if not inventory or ambient(step):
        return False
    for name, (size, mtime_ns, digest) in inventory.items():
        entry = files.get(name)
        if not entry or entry.get('kind') != 'file' or (entry['size'], entry['sha256'], entry['mtime_ns']) != (size, digest, mtime_ns):
            return False
    return True


def trusted(ctx, steps, manifest):
    """Saved stamps a receiver may consider, and the inventories that make them verified."""
    by_name = {s.name: s for s in steps}
    saved = {**manifest['stamps'], **manifest.get('incremental_stamps', {})}
    inventories = {n: v['output_inventory'] for n, v in saved.items()
                   if n in by_name and not verifiable(ctx, by_name[n]) and inventory_published(by_name[n], v, manifest['files'])}
    names = {n for n in saved if n in by_name and (verifiable(ctx, by_name[n]) or n in inventories)}
    return names, inventories


def ownership(ctx, steps, inventories=None):
    """Member-name prefix of each step-owned output path -> whether its owner is verifiable.

    A representative output only samples what its step writes, so an unverifiable step also
    claims that output's directory. Explicit outputs and declared roots override such claims.
    A step verified by its written inventory claims exactly the files it lists.
    """
    inventories = inventories or {}
    owners, weak = {}, {}
    # Deepest root first, as label() chooses; plain string prefixes keep this cheap per build.
    bases = sorted(((str(root), name) for name, (root, _) in roots(ctx).items()), key=lambda b: -len(b[0]))
    def member(path):
        text = str(Path(path).absolute())
        for base, name in bases:
            if text == base:
                return name
            if text.startswith(base + '/'):
                return name + '/' + text[len(base) + 1:]
        return None
    for step in steps:
        good = verifiable(ctx, step) or step.name in inventories
        for name in inventories.get(step.name, ()):
            owners[name] = owners.get(name, True)
        for path in dict.fromkeys([*map(Path, getattr(step, 'outputs', ())), *declared(ctx, step)]):
            name = member(path)
            if name is None:
                continue
            owners[name] = owners.get(name, True) and good
            if not good and name.count('/') >= 2:  # Never a whole root.
                weak[name.rpartition('/')[0]] = False
    return {**weak, **owners}


def unverified_member(member, owners):
    """True when the deepest step-owned prefix of a member belongs to an unverifiable step."""
    name = member
    while name:
        if name in owners:
            return not owners[name]
        name = name.rpartition('/')[0]
    return False


def publishable(files, owners):
    """Manifest members minus unverified-owned files and links into them."""
    kept = {m: e for m, e in files.items() if not unverified_member(m, owners)}
    return {m: e for m, e in kept.items()
            if not (e.get('kind') == 'link' and e['target'].startswith('member:') and unverified_member(e['target'][7:], owners))}


def certificate_key(ctx, step, fingerprint):
    from .build import Call
    if not declared(ctx, step) and all(isinstance(c, Call) for c in step.commands):
        return None
    return key(ctx, step, fingerprint, require_outputs=False)


def certified(ctx, step, fingerprint, stamp):
    """Existing bytes cannot acquire a new tool identity through stamp migration."""
    expected = certificate_key(ctx, step, fingerprint)
    if expected is None:
        from .build import Call
        return all(isinstance(c, Call) for c in step.commands)
    if stamp.get('checkpoint_key') != expected:
        return False
    if declared(ctx, step):
        try:
            observations = {}
            declarations, files = snapshot(ctx, step, Store(ctx.game), save_blobs=False, observations=observations)
            good = stamp.get('checkpoint_inventory') == inventory_identity(declarations, files)
            if good:
                ctx.__dict__.setdefault('retention_observations', {})[step.name] = observations
            return good
        except (OSError, ValueError, RuntimeError):
            return False
    return True


def local_incremental(ctx, step, fingerprint, stamp):
    """Continue compatible existing state without inventing a producer tool/cache certificate."""
    observed = getattr(ctx, 'checkpoint_observed_context', None)
    allowance = (stamp.get('checkpoint_incremental_context') == observed if stamp.get('checkpoint_incremental_context')
                 else getattr(ctx, 'checkpoint_incremental_compatible', False))
    return (allowance and not stamp.get('checkpoint_key') and not stamp.get('touched')
            and stamp.get('fingerprint') == fingerprint)


def migrate_boundary(ctx, step, current, input_state, previous, done, *, echo=print):
    """@cc [owner:fontanierh,label:correctness] verified-input-boundary-migration
    A dependency-boundary migration MUST reproduce the previous declaration's full current
    fingerprint and verify its existing outputs. Only dependency names MAY differ. Fresh
    receiving inputs MUST still match before metadata publication. Retained output bytes MUST
    remain compatibility-only state; migration MUST NOT invent produced task/tool provenance.
    """
    old_needs = getattr(step, 'checkpoint_previous_needs', None)
    if old_needs is None or previous.get('fingerprint') == current:
        return previous
    if not previous:
        # Historical metadata is evidence for this equivalence check, never a current certificate.
        retained = ctx.out / '.state/checkpoint.json'
        if retained.is_file():
            saved = Store(ctx.game).load(read_json(retained)['key'])
            previous = {**saved['stamps'], **saved.get('incremental_stamps', {})}.get(step.name, {})
    if not previous:
        return previous
    from dataclasses import replace
    from .build import fingerprint, outputs_present, result
    old_step = replace(step, needs=list(old_needs), checkpoint_previous_needs=None)
    old_key = fingerprint(old_step, done)
    if (old_key != previous.get('fingerprint') or not outputs_present(step)
            or (step.products and not build_products.valid_records(step, previous.get('products', {})))
            or not (certified(ctx, old_step, old_key, previous) or local_incremental(ctx, old_step, old_key, previous))):
        return previous
    if fingerprint(step, done) != current:
        raise CheckpointError('Inputs changed during dependency migration')
    migrated = dict(previous, fingerprint=current, input_state=input_state,
                    checkpoint_incremental_context=getattr(ctx, 'checkpoint_observed_context', None),
                    checkpoint_migrated_from=old_key,
                    checkpoint_migration_result=result(old_step, old_key, previous))
    migrated.pop('checkpoint_key', None)
    migrated.pop('checkpoint_inventory', None)
    atomic_json(ctx.stamps / (step.name + '.json'), migrated)
    echo(step.name + ': preserved existing import after verified dependency migration')
    return migrated
