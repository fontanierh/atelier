class Record:
    def __init__(self):
        self.data = bytearray()

    def word(self, value):
        self.data.extend(struct.pack('<I', value & 0xffffffff))

    def words(self, values):
        for value in values:
            self.word(value)

    def scalar(self, value):
        self.data.extend(struct.pack('<f', value))

    def scalars(self, values):
        for value in values:
            self.scalar(value)

    def raw(self, value):
        if isinstance(value, str):
            value = value.encode()
        self.word(len(value))
        self.data.extend(value)

    def optional(self, value):
        self.word(value is not None)
        if value is not None:
            self.scalar(value)

    def graph(self, count, first=0., last=1., values=None):
        keys = [first + (last-first)*i/(count-1) for i in range(count)]
        self.scalars(keys)
        self.scalars(keys if values is None else values)

    def remap(self, variant):
        self.graph(16, 0., 3.1415927410125732, [1.+variant*i/150 for i in range(16)])
        self.graph(16, 0., 3.1415927410125732)
        self.scalar(variant*.12)


def fbits(value):
    return struct.unpack('<I', struct.pack('<f', value))[0]


def from_bits(value):
    return struct.unpack('<f', struct.pack('<I', value))[0]


