    pad_levels = [0., -0., .5, from_bits(0x3f000001), 1., -1., from_bits(0x7fc12345)]
    for case in range(128):
        def build(w, case=case):
            stored = case % 25
            count = (case*7) % (stored+1)
            w.words((stored, count))
            for slot in range(stored):
                w.words((fbits(pad_levels[(slot+case) % len(pad_levels)]), rng.getrandbits(32),
                         (0, 1, 12, 24, 0xffffffff)[slot % 5], (0, 1, 2, 3, 0xffffffff, 0x80000000)[slot % 6]))
            w.word(160)
            for tick in range(160):
                # Three-call suppression, 24/12 repeat, resize growth/reset and
                # shorter polls with retained native initialized storage.
                size = 24 if tick < 90 else (0, 4, 24, 8, 24, 1)[tick % 6]
                w.word(size)
                w.scalars([pad_levels[((tick//(4+slot%5))+slot+case) % len(pad_levels)] for slot in range(size)])
        add(2, 'button suppression/repeat/wrapping and retained storage', build)

    axes = (-32768, -32767, -8193, -8192, -8191, -33, -32, -1, 0, 1, 32, 33, 8191, 8192, 8193, 32766, 32767)
    xbox_states = [(buttons, lt, rt, lx, ly, rx, ry, device)
                   for buttons in (0, 0xffff, 0x03ff, 0xf000, 0x0c00)
                   for lt, rt in ((0, 0), (1, 254), (127, 128), (255, 255))
                   for lx, ly in itertools.product(axes, repeat=2)
                   for rx, ry, device in ((lx, ly, 0), (-lx if lx != -32768 else 32767, -ly if ly != -32768 else 32767, 1))]
