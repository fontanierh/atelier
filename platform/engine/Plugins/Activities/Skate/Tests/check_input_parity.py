def build_probes(output, target_dir):
    native = PLUGIN/'Source/AtelierSkate/Private/Native'
    cpp = output/'input-cpp'
    sources = [native/f'{name}.cpp' for name in ('NativeMath', 'AnimationName', 'Intents', 'Input', 'InputIntentions')]
    subprocess.run(['clang++', '-std=c++17', '-O2', '-ffp-contract=off', '-fno-fast-math', '-Wall', '-Wextra', '-Werror',
                    '-I', str(native), *(str(source) for source in sources), str(PLUGIN/'Tests/Native/input_probe.cpp'), '-o', str(cpp)], check=True)
    rust = build_probe(output, 'input-reference', PLUGIN/'Tests/Reference/input_probe.rs', target_dir)
    return cpp, rust


def first_failing_command(cpp, rust, inputs, cases):
    # Replay prefixes only after failure to report the concrete triggering case.
    lower, upper = 1, len(cases)
    while lower < upper:
        middle = (lower+upper)//2
        end = cases[middle-1]['input_offset'] + cases[middle-1]['input_bytes']
        prefix = struct.pack('<I', middle) + inputs[4:end]
        expected = subprocess.check_output([str(rust)], input=prefix)
        actual = subprocess.check_output([str(cpp)], input=prefix)
        if actual == expected:
            lower = middle+1
        else:
            upper = middle
    return cases[lower-1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--target-dir', type=Path, required=True)
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    cpp, rust = build_probes(output, args.target_dir)
    inputs, cases = corpus()
    (output/'input.bin').write_bytes(inputs)
    (output/'cases.json').write_text(json.dumps(cases, indent=2)+'\n')
    expected = subprocess.check_output([str(rust)], input=inputs)
    actual = subprocess.check_output([str(cpp)], input=inputs)
    (output/'reference.bin').write_bytes(expected)
    (output/'cpp.bin').write_bytes(actual)
    if actual != expected:
        first = next((i for i, (a, b) in enumerate(zip(actual, expected)) if a != b), min(len(actual), len(expected)))
        report = dict(passed=False, first_byte=first, reference_length=len(expected), cpp_length=len(actual),
                      triggering_command=first_failing_command(cpp, rust, inputs, cases),
                      reference_hex=expected[max(0, first-16):first+32].hex(), cpp_hex=actual[max(0, first-16):first+32].hex())
        (output/'first-divergence.json').write_text(json.dumps(report, indent=2)+'\n')
        raise AssertionError(report)
    report = dict(passed=True, commands=len(cases), operations=dict(Counter(case['operation'] for case in cases)),
                  output_bytes=len(expected), comparison='all published values and retained controller/filter/latch words; exact bits, no tolerance',
                  inputs_sha256=hashlib.sha256(inputs).hexdigest(), outputs_sha256=hashlib.sha256(expected).hexdigest(),
                  reference_provenance='input-reference-provenance.json')
    (output/'result.json').write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps(report, indent=2), flush=True)


if __name__ == '__main__':
    main()
