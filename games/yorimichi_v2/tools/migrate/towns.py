"""Give Belmonte's and Brine Cove's runtime scenery groups their objects (world/regions/<region>/objects.toml).

    uv run python games/yorimichi_v2/tools/migrate/towns.py [--check]

A region's runtime file (unreal/Content/Data/<tag>/runtime.json) lists its scenery groups. The groups its objects.toml
already names are saved objects (objects.py). This converter adds an object for every other group the runtime draws, so
the region's scenery is saved and the runtime skips it (ABelmonteRegion::Spawn, AV2WorldManifest::CoversGroup). The saved
patch is built by the runtime's own code (UV2Migration::MigrateRegionGroups, V2MigrationTowns.cpp): non-plant groups keep
the district's bounds culling (ABelmonteRegion::SceneryTransforms), plant groups the gondola clearance
(ABelmonteRegion::PlantTransforms). This module mirrors those filters to count the instances and to cut the cell pieces.

Keys (V2MigrationTowns::GroupKeys): a group's mesh name, or "<mesh>#<index>" when another group of the file shares the
name. A group of more than PIECE_LIMIT instances the runtime draws is cut into 128 m cell pieces, "<key>@<x>_<y>" (the cell
of each instance's world position, floor of metres over 128); the pieces of one 512 m block form one object.

Each object is one editing unit: the adopted record that owns the group's mesh (assets/**/asset.toml outputs), which is
the ownership split already set by belmonte_units.py and brinecove_units.py (one building, one estate, one landmark or ship
tile, one ground, rock or town tile, one plant family). Plant units are named plant-<mesh> (their records are the shared
Japan plant records, listed as `model`). The id is object/<region>/<unit>. Existing entries are kept byte-identical: the
generated part follows them after the marker line, and a rerun replaces only what follows the marker.

A group is not saved, and is listed in the generated comments with its reason, when:
- `outside`: no instance lies inside the district (non-plant groups), or none survives the clearance (plant groups): the
  runtime draws none and MigrateRegionGroups refuses it.
- `no record`: no record owns its mesh, or no saved object names the recovered record that does.

A recovery (tools/migrate/recover.py) replaces an adopted record with records made from the donor sources; its mesh then
belongs to the new record, and the unit stays the one the region's saved object took (the placement record
object/<region>/<unit> that names the new record), so a recovery never renames a saved object.
"""
from __future__ import annotations

import argparse
import collections
import json
import math
import re
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
GAME = HERE.parents[1]
REPO = GAME.parents[1]
sys.path.insert(0, str(GAME / 'tools' / 'content'))
import records  # noqa: E402

MARKER = '# --- Generated by tools/migrate/towns.py: every other runtime group of the region (rerun to regenerate) ---'
REGIONS = {'belmonte': 'w16-belmonte', 'brinecove': 'w09-brinecove'}
TITLE = {'belmonte': 'Belmonte', 'brinecove': 'Brine Cove'}
DISTRICT_MARGIN_M = 100.0   # SceneryTransforms: the district's bounds_m with a 100 m margin, strict inside test
PIECE_LIMIT = 10000         # a plant group with more instances than this is cut into 128 m cell pieces
CELL_M = 128.0              # V2MigrationTowns::PieceCellM
BLOCK_CELLS = 4             # the cell pieces of a large plant group share an object per 4 x 4 cells (512 m)
REASONS = ('outside', 'no record')
PIECE = re.compile(r'^(?P<key>[^@]+)@(?P<x>-?\d+)_(?P<y>-?\d+)$')
CLEARANCE = GAME / 'unreal' / 'Content' / 'Data' / 'gondola' / 'runtime.json'


class TownError(RuntimeError):
    pass


def region_folder(tag: str, game: Path = GAME) -> Path:
    return game / 'world' / 'regions' / REGIONS[tag]


def runtime_path(tag: str, game: Path = GAME) -> Path:
    return game / 'unreal' / 'Content' / 'Data' / tag / 'runtime.json'


def mesh_name(entry: dict) -> str:
    """The mesh name a group is keyed by (FPaths::GetBaseFilename of its asset)."""
    return entry['asset'].rsplit('.', 1)[-1]


def group_keys(data: dict) -> list[str]:
    """Every group's key (V2MigrationTowns::GroupKeys): its mesh name, or mesh#index when the file shares the name."""
    names = [mesh_name(entry) for entry in data['groups']]
    counts = collections.Counter(names)
    return [name if counts[name] == 1 else f'{name}#{index}' for index, name in enumerate(names)]


def piece_key(key: str, cell_x: int, cell_y: int) -> str:
    return f'{key}@{cell_x}_{cell_y}'


def split_piece(key: str) -> tuple[str, tuple[int, int]] | None:
    match = PIECE.match(key)
    return None if match is None else (match['key'], (int(match['x']), int(match['y'])))


def package_records(game: Path) -> dict[str, list[str]]:
    """{package path: the record ids whose outputs list it}: adopted records, and the records a recovery made from donor
    sources in their place. Placements (actor packages) own no mesh."""
    owners: dict[str, list[str]] = collections.defaultdict(list)
    for path in sorted((game / 'assets').rglob('asset.toml')):
        data = tomllib.loads(path.read_text())
        if data.get('kind') == 'placement':
            continue
        for output in data.get('outputs', []):
            owners[output['package']].append(data['id'])
    return owners


def saved_units(game: Path) -> dict[str, dict[str, set[str]]]:
    """{region tag: {record id: the units of the region's saved objects (object/<tag>/<unit>) that name it}}."""
    units: dict[str, dict[str, set[str]]] = collections.defaultdict(lambda: collections.defaultdict(set))
    for path in sorted((game / 'assets/object').glob('*/*/asset.toml')):
        data = tomllib.loads(path.read_text())
        _, tag, unit = data['id'].split('/', 2)
        for ref in data.get('references', []):
            units[tag][ref].add(unit)
    return units


def covered_groups(text: str) -> set[str]:
    """The keys the region's existing objects (the text before the marker) already save."""
    covered = set()
    for item in tomllib.loads(text).get('objects', []):
        covered |= set(item.get('groups', []))
        if 'group' in item:
            covered.add(item['group'])
    return covered


def origin_of(data: dict) -> tuple[float, float]:
    return data['origin_cm'][0], data['origin_cm'][1]


def world_m(data: dict, translation_cm: list[float]) -> tuple[float, float]:
    """A placement's world position in metres: x east, y north (the Unreal y is negated, as InClearance reads it)."""
    ox, oy = origin_of(data)
    return (ox + translation_cm[0]) / 100.0, -(oy + translation_cm[1]) / 100.0


def in_bounds(data: dict, x: float, y: float) -> bool:
    """SceneryTransforms' test: inside the district's bounds_m with its 100 m margin (strict)."""
    bounds = data['bounds_m']
    return (bounds[0] - DISTRICT_MARGIN_M < x < bounds[2] + DISTRICT_MARGIN_M
            and bounds[1] - DISTRICT_MARGIN_M < y < bounds[3] + DISTRICT_MARGIN_M)


def in_district(data: dict, entry: dict) -> int:
    """How many of a non-plant group's instances SceneryTransforms keeps."""
    return sum(1 for item in entry['transforms'] if in_bounds(data, *world_m(data, item['translation_cm'])))


def in_clearance(segments: list, x: float, y: float) -> bool:
    """ABelmonteRegion::InClearance for the gondola's clearance segments: [ax, ay, bx, by, radius] in metres."""
    for ax, ay, bx, by, radius in segments:
        if x < min(ax, bx) - radius or x > max(ax, bx) + radius or y < min(ay, by) - radius or y > max(ay, by) + radius:
            continue   # outside the segment's box: no point of it lies within the radius
        vx, vy = bx - ax, by - ay
        length = vx * vx + vy * vy
        t = 0.0 if length == 0 else max(0.0, min(1.0, ((x - ax) * vx + (y - ay) * vy) / length))
        px, py = ax + t * vx, ay + t * vy
        if (x - px) ** 2 + (y - py) ** 2 <= radius * radius:
            return True
    return False


def kept_cells(data: dict, entry: dict, segments: list) -> dict[tuple[int, int], int]:
    """The instances the runtime draws from a group, counted per 128 m cell: a plant group's outside the gondola clearance
    (ABelmonteRegion::PlantTransforms), any other group's inside the district (SceneryTransforms)."""
    cells: dict[tuple[int, int], int] = collections.Counter()
    for item in entry['transforms']:
        x, y = world_m(data, item['translation_cm'])
        keep = not in_clearance(segments, x, y) if entry['plant'] else in_bounds(data, x, y)
        if keep:
            cells[(math.floor(x / CELL_M), math.floor(y / CELL_M))] += 1
    return dict(cells)


plant_cells = kept_cells


def clearance_segments() -> list:
    return json.loads(CLEARANCE.read_text())['clearance_segments_m']


def unit_of(record: str) -> str:
    """The unit an adopted record names: adopted/<area>/<unit>."""
    return record.split('/', 2)[2]


def record_unit(tag: str, key: str, record: str, units: dict[str, set[str]] | None) -> str | None:
    """An adopted record's own unit, or the one saved object unit that names a recovered record (None: no saved object
    names it yet; the split that made it gives it one)."""
    if record.startswith('adopted/'):
        return unit_of(record)
    named = sorted({unit.removesuffix('-planting') for unit in (units or {}).get(record, ())})   # see classify `taken`
    if len(named) > 1:
        raise TownError(f'{tag}: {key} is owned by {record}, which saved objects {named} of {tag} all name; a recovered '
                        'record must keep the one unit its saved object took')
    return named[0] if named else None


def kebab(name: str) -> str:
    return name.lower().replace('_', '-')


def cell_label(cell: tuple[int, int]) -> str:
    def part(value: int) -> str:
        return ('m' if value < 0 else '') + str(abs(value))
    return f'{part(cell[0])}-{part(cell[1])}'


def classify(tag: str, data: dict, covered: set[str], owners: dict[str, list[str]], taken: set[str] = frozenset(),
             segments: list | None = None, saved: dict[str, set[str]] | None = None) -> dict:
    """Sort every group the region's objects do not already save into object units, or a reason not to save it.

    `taken` holds the object ids the region already has: a unit whose id is taken (the lighthouse's planting, kept apart
    from the lighthouse object as its objects.toml says) takes the suffix `-planting`. `saved` ({record id: units},
    saved_units) names the unit of a recovered record. Returns {'units': {unit: [(key,
    record ids, instances)]}, 'blocked': {reason: [(key, detail)]}, 'handled': the keys accounted for, 'covered': int,
    'instances': int}; a plant group cut into pieces is handled through its pieces."""
    keys = group_keys(data)
    if segments is None:
        segments = clearance_segments()
    units: dict[str, list] = collections.defaultdict(list)
    blocked: dict[str, list] = {reason: [] for reason in REASONS}
    handled: set[str] = set()   # the group keys accounted for (a plant group cut into pieces is handled by its pieces)
    counted = {'covered': 0, 'instances': 0}

    def add(unit: str, key: str, records_for: list[str], count: int) -> None:
        if f'object/{tag}/{unit}' in taken:
            unit += '-planting'
        units[unit].append((key, records_for, count))
        counted['instances'] += count
        handled.add(key.split('@', 1)[0])

    for entry, key in zip(data['groups'], keys):
        if key in covered:
            counted['covered'] += 1
            handled.add(key)
            continue
        package = entry['asset'].rsplit('.', 1)[0]
        adopted = sorted(owners.get(package, []))
        # A plant group keeps its own family unit; any other group its record unit (one building, tile or family).
        whole_unit = adopted and (f'plant-{kebab(mesh_name(entry))}' if entry['plant'] else
                                  record_unit(tag, key, adopted[0], saved))
        if not whole_unit:
            blocked['no record'].append((key, package))
            handled.add(key)
            continue
        cells = kept_cells(data, entry, segments)
        total = sum(cells.values())
        if total == 0:
            reason = 'no instance survives the gondola clearance' if entry['plant'] else 'no instance inside the district'
            blocked['outside'].append((key, reason))
            handled.add(key)
            continue
        if total <= PIECE_LIMIT:
            add(whole_unit, key, adopted, total)
            continue
        # Over the limit: one piece per 128 m cell the instances lie in; the pieces of one 512 m block form an object.
        for cell in sorted(cells):
            piece = piece_key(key, *cell)
            if piece in covered:
                counted['covered'] += 1
                handled.add(key)
                continue
            block = (math.floor(cell[0] / BLOCK_CELLS), math.floor(cell[1] / BLOCK_CELLS))
            add(f'{whole_unit}-{cell_label(block)}', piece, adopted, cells[cell])
    return {'units': dict(sorted(units.items())), 'blocked': blocked, 'handled': handled, **counted}


def quote(text: str) -> str:
    return json.dumps(text)


def object_entry(tag: str, unit: str, members: list) -> list[str]:
    names = [name for name, _, _ in members]
    records_for = sorted({rid for _, rids, _ in members for rid in rids})
    groups = f'group = {quote(names[0])}' if len(names) == 1 else \
        'groups = [' + ', '.join(quote(n) for n in names) + ']'
    model = f'model = {quote(records_for[0])}' if len(records_for) == 1 else \
        'model = [' + ', '.join(quote(r) for r in records_for) + ']'
    plural = '' if len(names) == 1 else 's'
    about = f'{TITLE[tag]} {unit} ({len(names)} group{plural})'
    return [
        '[[objects]]',
        f'id = {quote("object/" + tag + "/" + unit)}',
        groups,
        model,
        f'about = {quote(about)}',
        '',
    ]


def generated_text(tag: str, result: dict) -> str:
    lines = [MARKER, '']
    for unit, members in result['units'].items():
        lines += object_entry(tag, unit, members)
    lines.append('# Not saved, by reason:')
    for reason in REASONS:
        for name, detail in result['blocked'][reason]:
            lines.append(f'# {reason}: {name} ({detail})')
    return '\n'.join(lines) + '\n'


def split_head(text: str) -> str:
    """The region's own text, before the generated part."""
    head, found, _ = text.partition(MARKER)
    return head if found else (text if text.endswith('\n') else text + '\n')


def render(tag: str, head: str, data: dict, owners: dict[str, list[str]],
           units: dict[str, set[str]] | None = None) -> tuple[str, dict]:
    taken = {item['id'] for item in tomllib.loads(head).get('objects', [])}
    result = classify(tag, data, covered_groups(head), owners, taken, saved=units)
    return head + generated_text(tag, result), result


def check_result(tag: str, data: dict, result: dict, head: str) -> None:
    """Every runtime group is in exactly one place: an existing object, a generated unit (or its cell pieces), a reason."""
    covered = covered_groups(head)
    generated = [key for members in result['units'].values() for key, _, _ in members]
    blocked = [key for reason in REASONS for key, _ in result['blocked'][reason]]
    listed = collections.Counter(generated + blocked)
    dup = [n for n, c in listed.items() if c > 1]
    if dup:
        raise TownError(f'{tag}: groups listed twice: {dup[:5]}')
    if set(listed) & covered:
        raise TownError(f'{tag}: a saved group is listed again')
    keys = group_keys(data)
    missing = sorted({k for k in keys if k not in covered and k not in result['handled']})
    if missing:
        raise TownError(f'{tag}: {len(missing)} group(s) unaccounted for, e.g. {missing[:3]}')
    units = list(result['units'])
    if len(units) != len(set(units)):
        raise TownError(f'{tag}: duplicate unit')
    existing = {item['id'] for item in tomllib.loads(head).get('objects', [])}
    if existing & {f'object/{tag}/{unit}' for unit in units}:
        raise TownError(f'{tag}: an object id is already taken by the region')


def check_group_keys(tag: str, names: list[str], data: dict) -> None:
    """The keys an object names must be groups of the runtime file, or cell pieces of a plant group."""
    keys = set(group_keys(data))
    for name in names:
        piece = split_piece(name)
        base = piece[0] if piece else name
        if base not in keys or (piece is not None and piece[0] not in keys):
            raise TownError(f'{tag}: {name} is no group key of {tag}/runtime.json')


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--check', action='store_true', help='exit 1 when the files differ from the generated text')
    parser.add_argument('--region', action='append', choices=sorted(REGIONS), help='only this region (repeatable)')
    args = parser.parse_args(argv)
    owners, units = package_records(GAME), saved_units(GAME)
    stale = []
    for tag in args.region or sorted(REGIONS):
        path = region_folder(tag) / 'objects.toml'
        current = path.read_text()
        head = split_head(current)
        data = json.loads(runtime_path(tag).read_text())
        text, result = render(tag, head, data, owners, units[tag])
        check_result(tag, data, result, head)
        count = sum(len(m) for m in result['units'].values())
        pieces = sum(1 for m in result['units'].values() for key, _, _ in m if '@' in key)
        print(f'{tag}: {count} group(s) (pieces {pieces}) in {len(result["units"])} object(s), {result["covered"]} already '
              f'saved, {result["instances"]} instances; not saved: ' +
              ', '.join(f'{r} {len(result["blocked"][r])}' for r in REASONS))
        if current == text:
            continue   # a no-op run writes nothing (CONTRACTS yorimichi-v2-targeted-authoring)
        if args.check:
            stale.append(path)
        else:
            path.write_text(text)
    if stale:
        print('stale: ' + ', '.join(str(p) for p in stale) + ' (rerun towns.py)', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
