"""Give Belmonte's and Brine Cove's remaining runtime scenery groups their objects (world/regions/<region>/objects.toml).

    uv run python games/yorimichi_v2/tools/migrate/towns.py [--check]

A region's runtime file (unreal/Content/Data/<tag>/runtime.json) lists its scenery groups. The groups its objects.toml
already names are saved objects (objects.py). This converter adds an object for every other group that the runtime draws,
so the region's scenery is saved as objects and the runtime skips it (ABelmonteRegion::Spawn, CoversGroup). The saved
patch is built by the runtime's own code (UV2Migration::MigrateRegionGroups, ABelmonteRegion::SceneryTransforms), so a
saved group draws exactly the instances the runtime would draw: the district's bounds culling is applied there too.

Each generated object is one editing unit: the adopted record that owns the group's mesh (assets/**/asset.toml outputs),
which is the ownership split already set by belmonte_units.py and brinecove_units.py (one building, one estate, one
landmark or ship tile, one ground, rock or town tile, one plant family). The id is object/<area>/<unit>; `model` is that
record (a list when a unit owns several). Existing entries are kept byte-identical: the generated part follows them after
the marker line, and a rerun replaces only what follows the marker.

A group is not saved, and is listed in the generated comments with its reason, when:
- `plant`: MigrateRegionGroups refuses plant groups (they join the island's tree lists), and the runtime filters their
  instances by the gondola clearance, which the saved patch does not apply. Needs a C++ change.
- `duplicate name`: the runtime skips a group by its mesh name, and MigrateRegionGroups keys its meshes by name, so two
  groups that share a mesh name cannot be saved one at a time. Needs a C++ change (match groups by index).
- `outside`: no instance lies inside the district, so the runtime draws none and MigrateRegionGroups refuses it.
- `no record`: no adopted record owns its mesh.
"""
from __future__ import annotations

import argparse
import collections
import json
import re
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
GAME = HERE.parents[1]
REPO = GAME.parents[1]
sys.path.insert(0, str(GAME / 'tools' / 'content'))
import records  # noqa: E402

MARKER = '# --- Generated by tools/migrate/towns.py: every other runtime group of the region (rerun to regenerate) ---'
REGIONS = {'belmonte': 'w16-belmonte', 'brinecove': 'w09-brinecove'}
TITLE = {'belmonte': 'Belmonte', 'brinecove': 'Brine Cove'}
DISTRICT_MARGIN_M = 100.0   # SceneryTransforms: the district's bounds_m with a 100 m margin, strict inside test
REASONS = ('plant', 'duplicate name', 'outside', 'no record')


class TownError(RuntimeError):
    pass


def region_folder(tag: str, game: Path = GAME) -> Path:
    return game / 'world' / 'regions' / REGIONS[tag]


def runtime_path(tag: str, game: Path = GAME) -> Path:
    return game / 'unreal' / 'Content' / 'Data' / tag / 'runtime.json'


def mesh_name(entry: dict) -> str:
    """The mesh name ABelmonteRegion and MigrateRegionGroups key a group by (FPaths::GetBaseFilename of its asset)."""
    return entry['asset'].rsplit('.', 1)[-1]


def package_records(game: Path) -> dict[str, list[str]]:
    """{package path: the adopted record ids whose outputs list it}."""
    owners: dict[str, list[str]] = collections.defaultdict(list)
    for path in sorted((game / 'assets').rglob('asset.toml')):
        data = tomllib.loads(path.read_text())
        if data.get('kind') != 'adopted':
            continue
        for output in data.get('outputs', []):
            owners[output['package']].append(data['id'])
    return owners


def covered_groups(text: str) -> set[str]:
    """The mesh names the region's existing objects (the text before the marker) already save."""
    covered = set()
    for item in tomllib.loads(text).get('objects', []):
        covered |= set(item.get('groups', []))
        if 'group' in item:
            covered.add(item['group'])
    return covered


def in_district(data: dict, entry: dict) -> int:
    """How many of a group's instances SceneryTransforms keeps: inside the district's bounds, with its margin."""
    bounds = data['bounds_m']
    lo_x, lo_y = bounds[0] - DISTRICT_MARGIN_M, bounds[1] - DISTRICT_MARGIN_M
    hi_x, hi_y = bounds[2] + DISTRICT_MARGIN_M, bounds[3] + DISTRICT_MARGIN_M
    ox, oy, _ = data['origin_cm']
    kept = 0
    for item in entry['transforms']:
        x = (ox + item['translation_cm'][0]) / 100.0
        y = -(oy + item['translation_cm'][1]) / 100.0
        if lo_x < x < hi_x and lo_y < y < hi_y:
            kept += 1
    return kept


def unit_of(record: str) -> str:
    """The unit an adopted record names: adopted/<area>/<unit>."""
    return record.split('/', 2)[2]


def classify(tag: str, data: dict, covered: set[str], owners: dict[str, list[str]], taken: set[str] = frozenset()) -> dict:
    """Sort every group the region's objects do not already save into an object unit or a reason not to save it.

    `taken` holds the object ids the region already has: a unit whose id is taken (the lighthouse's planting, kept
    apart from the lighthouse object as its objects.toml says) takes the suffix `-planting`.

    Returns {'units': {unit: [(group, record ids, transforms kept)]}, 'blocked': {reason: [(group, detail)]},
    'covered': int, 'instances': int}, the per-group order of runtime.json kept."""
    names = collections.Counter(mesh_name(entry) for entry in data['groups'])
    units: dict[str, list] = collections.defaultdict(list)
    blocked: dict[str, list] = {reason: [] for reason in REASONS}
    counted = {'covered': 0, 'instances': 0}
    seen_shared: set[str] = set()
    for entry in data['groups']:
        name = mesh_name(entry)
        if name in covered:
            counted['covered'] += 1
            continue
        if entry['plant']:
            blocked['plant'].append((name, f"{len(entry['transforms'])} transforms, not culled by bounds"))
            continue
        if names[name] > 1:
            if name not in seen_shared:
                seen_shared.add(name)
                shared = [e for e in data['groups'] if mesh_name(e) == name]
                blocked['duplicate name'].append((name, f"{len(shared)} groups, {sum(len(e['transforms']) for e in shared)} transforms"))
            continue
        kept = in_district(data, entry)
        if kept == 0:
            blocked['outside'].append((name, 'no instance inside the district'))
            continue
        package = entry['asset'].rsplit('.', 1)[0]
        adopted = sorted(owners.get(package, []))
        if not adopted:
            blocked['no record'].append((name, package))
            continue
        unit = unit_of(adopted[0])
        if f'object/{tag}/{unit}' in taken:
            unit += '-planting'
        units[unit].append((name, adopted, kept))
        counted['instances'] += kept
    return {'units': dict(sorted(units.items())), 'blocked': blocked, **counted}


def quote(text: str) -> str:
    return json.dumps(text)


def object_entry(tag: str, unit: str, members: list) -> list[str]:
    names = [name for name, _, _ in members]
    records_for = sorted({rid for _, rids, _ in members for rid in rids})
    groups = f'group = {quote(names[0])}' if len(names) == 1 else \
        'groups = [' + ', '.join(quote(n) for n in names) + ']'
    model = f'model = {quote(records_for[0])}' if len(records_for) == 1 else \
        'model = [' + ', '.join(quote(r) for r in records_for) + ']'
    plural = '' if len(names) == 1 else 's'
    about = f'{TITLE[tag]} {unit} ({len(names)} group{plural})'
    return [
        '[[objects]]',
        f'id = {quote("object/" + tag + "/" + unit)}',
        groups,
        model,
        f'about = {quote(about)}',
        '',
    ]


def generated_text(tag: str, result: dict) -> str:
    lines = [MARKER, '']
    for unit, members in result['units'].items():
        lines += object_entry(tag, unit, members)
    lines.append('# Not saved, by reason (the runtime keeps drawing these until the C++ side accepts them):')
    for reason in REASONS:
        for name, detail in result['blocked'][reason]:
            lines.append(f'# {reason}: {name} ({detail})')
    return '\n'.join(lines) + '\n'


def split_head(text: str) -> str:
    """The region's own text, before the generated part."""
    head, found, _ = text.partition(MARKER)
    return head if found else (text if text.endswith('\n') else text + '\n')


def render(tag: str, head: str, data: dict, owners: dict[str, list[str]]) -> tuple[str, dict]:
    taken = {item['id'] for item in tomllib.loads(head).get('objects', [])}
    result = classify(tag, data, covered_groups(head), owners, taken)
    return head + generated_text(tag, result), result


def check_result(tag: str, data: dict, result: dict, head: str) -> None:
    """Every runtime group is in exactly one place: an existing object, a generated unit, a reason, or drawn by no one."""
    covered = covered_groups(head)
    generated = [name for members in result['units'].values() for name, _, _ in members]
    blocked = [name for reason in REASONS for name, _ in result['blocked'][reason]]
    listed = collections.Counter(generated + blocked)
    dup = [n for n, c in listed.items() if c > 1]
    if dup:
        raise TownError(f'{tag}: groups listed twice: {dup[:5]}')
    if set(listed) & covered:
        raise TownError(f'{tag}: a saved group is listed again')
    names = [mesh_name(entry) for entry in data['groups']]
    missing = sorted({n for n in names if n not in covered and n not in listed})
    if missing:
        raise TownError(f'{tag}: {len(missing)} group(s) unaccounted for, e.g. {missing[:3]}')
    units = list(result['units'])
    if len(units) != len(set(units)):
        raise TownError(f'{tag}: duplicate unit')
    existing = {item['id'] for item in tomllib.loads(head).get('objects', [])}
    if existing & {f'object/{tag}/{unit}' for unit in units}:
        raise TownError(f'{tag}: an object id is already taken by the region')


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--check', action='store_true', help='exit 1 when the files differ from the generated text')
    parser.add_argument('--region', action='append', choices=sorted(REGIONS), help='only this region (repeatable)')
    args = parser.parse_args(argv)
    owners = package_records(GAME)
    stale = []
    for tag in args.region or sorted(REGIONS):
        path = region_folder(tag) / 'objects.toml'
        head = split_head(path.read_text())
        data = json.loads(runtime_path(tag).read_text())
        text, result = render(tag, head, data, owners)
        check_result(tag, data, result, head)
        count = sum(len(m) for m in result['units'].values())
        print(f'{tag}: {count} group(s) in {len(result["units"])} object(s), {result["covered"]} already saved, '
              f'{result["instances"]} instances; not saved: ' +
              ', '.join(f'{r} {len(result["blocked"][r])}' for r in REASONS))
        if args.check:
            if path.read_text() != text:
                stale.append(path)
        else:
            path.write_text(text)
    if stale:
        print('stale: ' + ', '.join(str(p) for p in stale) + ' (rerun towns.py)', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
