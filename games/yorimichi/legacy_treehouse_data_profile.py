"""Observation-only qualification of the exact Treehouse canopy JSON data step.

This profile neither executes plain-Python code nor claims captured-native support,
input availability, cache publication or completion authority.
"""
from dataclasses import dataclass
import os
from pathlib import Path
import stat


PARENTS = ('Tree_Canopy_Maple', 'Tree_Canopy_Crimson', 'Tree_Canopy_Amber', 'Tree_Canopy_Ginkgo')


class UnsupportedTreehouseData(ValueError):
    """The declaration is outside the reviewed canopy JSON aggregation role."""


@dataclass(frozen=True)
class TreehouseData:
    step: str
    script: Path
    arguments: tuple[str, ...]
    raw_inputs: tuple[Path, ...]
    produced_inputs: tuple[Path, ...]
    code_inputs: tuple[Path, ...]
    products: tuple[tuple[str, tuple[Path, ...]], ...]


def _source(checkout, path):
    from atelier.build_v2.controller_client import MAX_SOURCE_FILE_BYTES, _read_at
    try:
        relative = Path(path).relative_to(checkout).as_posix()
        return _read_at(checkout, relative, MAX_SOURCE_FILE_BYTES)
    except (OSError, ValueError) as error:
        raise UnsupportedTreehouseData(f'data source is absent, linked or invalid: {path}') from error


def _output(path):
    from atelier.build_v2.controller_client import _open_root
    current = path
    while True:
        try:
            info = current.lstat()
        except FileNotFoundError:
            if current == current.parent:
                raise UnsupportedTreehouseData(f'data output has no real ancestor: {path}') from None
            current = current.parent
            continue
        expected = stat.S_ISDIR if current != path else stat.S_ISREG
        if not expected(info.st_mode):
            raise UnsupportedTreehouseData(f'data output is linked or has an invalid role: {current}')
        if stat.S_ISDIR(info.st_mode):
            try:
                descriptor = _open_root(current)
                os.close(descriptor)
            except OSError as error:
                raise UnsupportedTreehouseData(f'data output ancestry is linked: {current}') from error
            break
        current = current.parent


def qualify_treehouse_data(step, *, checkout: Path, output_root: Path) -> TreehouseData:
    """@cc [owner:fontanierh,label:correctness;safety] closed-treehouse-data-observation
    Qualification MUST bind only the actual plain-Python canopy data declaration, exact
    argv/source/input/product/read roles and cacheTrue/auditFalse/no-verifier/no-batch controls.
    Fixed sources MUST use bounded anchored nofollow reads before inert import discovery;
    cold output tails MUST remain absent and warm generated bytes unread/unchanged.
    It MUST NOT execute scripts/helpers, add recolour/native authority, normalize inputs,
    or grant cache/publication/frame/full-Graph/Finish authority. See actual-Graph tests.
    """
    from atelier import build, build_inputs, build_products
    from atelier.build_v2.controller_client import _open_root

    checkout, output_root = Path(checkout), Path(output_root)
    if (type(step) is not build.Step or step.name != 'world.treehouse_trees.data'
            or not checkout.is_absolute() or not output_root.is_absolute()
            or checkout == Path(checkout.anchor) or output_root == Path(output_root.anchor)):
        raise UnsupportedTreehouseData('not the exact Treehouse data Step and absolute anchors')
    try:
        descriptor = _open_root(checkout)
        os.close(descriptor)
    except OSError as error:
        raise UnsupportedTreehouseData('data checkout is not a real anchored directory') from error
    game = checkout / 'games/yorimichi'
    world = game / 'world'
    regions = world / 'regions'
    studio = checkout / 'platform/studio/atelier'
    script = regions / 'treehouse/canopy_data.py'
    output = output_root / 'treehouse-data/canopy/trees.json'
    produced = tuple(output_root / 'treehouse-data/canopy/records' / f'{parent}.json' for parent in PARENTS)
    arguments = ('--output', str(output), *(item for record in produced for item in ('--record', str(record))))
    if len(set(produced)) != 4 or output in produced or any(output in record.parents for record in produced):
        raise UnsupportedTreehouseData('data record/output roles overlap')
    _output(output)
    for record in produced:
        _output(record)

    defaults = {
        'deferred_inputs': [], 'needs': [], 'after': [], 'outputs': [], 'heavy': False,
        'pool_roots': [], 'explicit': False, 'verify': None, 'cutoff': False, 'references': [],
        'cache': True, 'audit': False, 'optional_inputs': [], 'queries': [], 'toolchain': False,
        'batch': None, 'cook_recovery': None, 'checkpoint_previous_needs': None,
        'checkpoint_restore': None, 'checkpoint_outputs': (), 'candidate_scope': None,
        'replan': False, 'controller': None,
    }
    dynamic = {'name', 'commands', 'inputs', 'about', 'products', 'reads'}
    if (set(vars(step)) - dynamic != set(defaults)
            or any(vars(step)[name] != value for name, value in defaults.items())
            or getattr(step, '_query_bindings', None) not in (None, ())
            or step.reads != [f'treehouse.canopy_record.{parent}' for parent in PARENTS]):
        raise UnsupportedTreehouseData('data Step controls, flags or ordered reads differ')
    if len(step.commands) != 1:
        raise UnsupportedTreehouseData('data requires exactly one original Python command')
    command = step.commands[0]
    if (type(command) is not build.Python or set(vars(command)) != {'script', 'args'}
            or type(command.script) is not type(script) or command.script != script
            or type(command.args) is not tuple or command.args != arguments
            or not all(type(value) is str for value in command.args)):
        raise UnsupportedTreehouseData('data script or exact argument order differs')
    if len(step.products) != 1:
        raise UnsupportedTreehouseData('data requires one original Product')
    product = step.products[0]
    if (type(product) is not build_products.Product
            or set(vars(product)) != {'name', 'paths', 'collection', 'bounds', 'optional_paths'}
            or product.name != 'treehouse.canopy_dimensions' or product.paths != (output,)
            or product.collection is not None or product.bounds is not None or product.optional_paths):
        raise UnsupportedTreehouseData('data product name or complete output ownership differs')

    # Precheck declared roles before the existing inert scanner; no unknown imported
    # source is claimed prechecked by this final closure/declaration comparison.
    for source in step.inputs:
        _source(checkout, source)
    local = build_inputs.local_imports(script, (world, regions))
    local_root = Path(local[0]).parents[3] if local else script.parents[3]
    code = []
    for path in local:
        try:
            mapped = studio / path.relative_to(local_root / 'platform/studio/atelier')
        except ValueError:
            try:
                mapped = world / path.relative_to(local_root / 'games/yorimichi/world')
            except ValueError as error:
                raise UnsupportedTreehouseData(f'data code path has an unexpected source root: {path}') from error
        code.append(mapped)
    if (type(step.inputs) is not list or len(step.inputs) != len(code) or any(
            type(actual) is not type(expected) or actual != expected
            for actual, expected in zip(step.inputs, code))):
        raise UnsupportedTreehouseData('data original enriched source membership/order differs')
    for source in code:
        _source(checkout, source)
    return TreehouseData(step.name, script, arguments, (), produced, tuple(code),
                         ((product.name, product.paths),))
